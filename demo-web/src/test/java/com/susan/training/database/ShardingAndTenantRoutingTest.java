package com.susan.training.database;

import com.susan.training.persistence.shard.ShardOrderView;
import com.susan.training.persistence.shard.ShardedOrderService;
import com.susan.training.persistence.tenant.TenantContext;
import com.susan.training.persistence.tenant.TenantRoutingDataSource;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import javax.sql.DataSource;
import java.math.BigDecimal;
import java.util.LinkedHashMap;
import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * 不依赖外部 PostgreSQL，验证分片路由和动态数据源切换算法。
 */
class ShardingAndTenantRoutingTest {
    @Test
    void shardRoutesSingleReadsAndMergesCrossShardQuery() {
        JdbcTemplate jdbcTemplate = new JdbcTemplate(h2DataSource("shard_demo"));
        createShardTables(jdbcTemplate);
        ShardedOrderService service = new ShardedOrderService(jdbcTemplate);

        ShardOrderView first = service.create(
                "demo",
                "C-SHARD",
                new BigDecimal("10.00")
        );
        ShardOrderView second = service.create(
                "demo",
                "C-SHARD",
                new BigDecimal("20.00")
        );

        assertThat(service.findByOrderNo("demo", first.orderNo()))
                .extracting(ShardOrderView::shard)
                .isEqualTo(service.route(first.orderNo()));
        assertThat(service.findByCustomer("demo", "C-SHARD"))
                .extracting(ShardOrderView::orderNo)
                .contains(first.orderNo(), second.orderNo());
    }

    @Test
    void routingDataSourceIsolatesTenantRows() {
        DriverManagerDataSource acme = h2DataSource("tenant_acme");
        DriverManagerDataSource globex = h2DataSource("tenant_globex");
        new JdbcTemplate(acme).execute(
                "CREATE TABLE tenant_notes(note_key VARCHAR(64), note_value VARCHAR(200))"
        );
        new JdbcTemplate(globex).execute(
                "CREATE TABLE tenant_notes(note_key VARCHAR(64), note_value VARCHAR(200))"
        );
        new JdbcTemplate(acme).update(
                "INSERT INTO tenant_notes VALUES ('theme', 'blue')"
        );
        new JdbcTemplate(globex).update(
                "INSERT INTO tenant_notes VALUES ('theme', 'green')"
        );

        TenantRoutingDataSource routing = new TenantRoutingDataSource();
        Map<Object, Object> targets = new LinkedHashMap<>();
        targets.put("tenant_acme", acme);
        targets.put("tenant_globex", globex);
        routing.setTargetDataSources(targets);
        routing.setDefaultTargetDataSource(acme);
        routing.afterPropertiesSet();
        JdbcTemplate routed = new JdbcTemplate(routing);

        try {
            TenantContext.set("tenant_acme");
            assertThat(routed.queryForObject(
                    "SELECT note_value FROM tenant_notes WHERE note_key = 'theme'",
                    String.class
            )).isEqualTo("blue");

            TenantContext.set("tenant_globex");
            assertThat(routed.queryForObject(
                    "SELECT note_value FROM tenant_notes WHERE note_key = 'theme'",
                    String.class
            )).isEqualTo("green");
        } finally {
            // 模拟请求过滤器的 finally 清理，避免线程复用泄漏。
            TenantContext.clear();
        }
    }

    private DriverManagerDataSource h2DataSource(String database) {
        DriverManagerDataSource dataSource = new DriverManagerDataSource();
        dataSource.setDriverClassName("org.h2.Driver");
        dataSource.setUrl("jdbc:h2:mem:" + database + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1");
        dataSource.setUsername("sa");
        dataSource.setPassword("");
        return dataSource;
    }

    private void createShardTables(JdbcTemplate jdbcTemplate) {
        for (String table : new String[]{"shard_order_0", "shard_order_1"}) {
            jdbcTemplate.execute("""
                    CREATE TABLE %s (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        order_no VARCHAR(32) UNIQUE,
                        tenant_id VARCHAR(32),
                        customer_no VARCHAR(32),
                        amount NUMERIC(12, 2),
                        status VARCHAR(32),
                        created_at TIMESTAMP
                    )
                    """.formatted(table));
        }
    }
}
